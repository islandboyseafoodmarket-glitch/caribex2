export type PortalLanguage = "en" | "es";

export const PORTAL_LANGUAGE_KEY = "caribex-portal-language";

export function readPortalLanguage(): PortalLanguage {
  if (typeof window === "undefined") return "en";
  try {
    return window.localStorage.getItem(PORTAL_LANGUAGE_KEY) === "es" ? "es" : "en";
  } catch {
    return "en";
  }
}

export function savePortalLanguage(language: PortalLanguage) {
  if (typeof window === "undefined") return;
  try {
    window.localStorage.setItem(PORTAL_LANGUAGE_KEY, language);
  } catch {
    // Language selection still works for the current page if storage is unavailable.
  }
}

